    # ==================== DYNAMIC PACKAGE INSTALLER ====================
    @staticmethod
    def install_python_package(package_name: str) -> Dict[str, Any]:
        clean_pkg = re.sub(r"[^a-zA-Z0-9_\-\.\[\]=<>]", "", (package_name or "").strip())
        if not clean_pkg:
            return {"status": "error", "error": "Valid package name is required (e.g. 'tabulate', 'flask', 'qrcode')."}

        t0 = time.perf_counter()
        try:
            proc = subprocess.run(
                ["pip", "install", "--quiet", clean_pkg],
                capture_output=True,
                text=True,
                timeout=25.0,
            )
            elapsed = round((time.perf_counter() - t0) * 1000, 2)
            if proc.returncode == 0:
                return {
                    "status": "ok",
                    "package": clean_pkg,
                    "message": f"✅ Package '{clean_pkg}' installed successfully in VENOM AI environment ({elapsed} ms)!",
                    "stdout": proc.stdout[:600],
                }
            return {
                "status": "error",
                "error": proc.stderr[:500] or f"pip exited with code {proc.returncode}",
            }
        except Exception as e:
            return {"status": "error", "error": str(e)}

    # ==================== A-TO-Z GITHUB + RENDER FREE AUTO-DEPLOYER ====================
    @staticmethod
    def auto_deploy_github_and_render(
        github_token: str,
        repo_name: str,
        render_api_key: str = "",
        deploy_target: str = "venom_platform",
        custom_files: Optional[Dict[str, str]] = None,
    ) -> Dict[str, Any]:
        gh_token = (github_token or "").strip()
        if not gh_token:
            return {
                "status": "error",
                "error": "GitHub Personal Access Token (ghp_...) is required so VENOM AI can log into your GitHub, create the repo, and push the code.",
            }

        clean_repo = re.sub(r"[^a-zA-Z0-9_\-\.]", "-", (repo_name or "venom-ai-himanshu").strip()).strip("-")
        headers = {
            "Authorization": f"token {gh_token}",
            "Accept": "application/vnd.github.v3+json",
            "User-Agent": "VenomAI-AutoDeployer/3.0",
        }

        steps: List[str] = []

        # 1. Authenticate GitHub User
        r_user = requests.get("https://api.github.com/user", headers=headers, timeout=10)
        if r_user.status_code != 200:
            return {
                "status": "error",
                "error": f"GitHub Login Failed (HTTP {r_user.status_code}). Check your GitHub Token ('repo' scope required).",
            }
        owner = r_user.json().get("login")
        steps.append(f"✅ Logged into GitHub account: @{owner}")

        # 2. Create GitHub Repository
        r_create = requests.post(
            "https://api.github.com/user/repos",
            headers=headers,
            json={
                "name": clean_repo,
                "description": "VENOM AI Platform — Developed by Himanshu (Auto-Deployed by Venom AI)",
                "private": False,
                "auto_init": True,
            },
            timeout=12,
        )
        if r_create.status_code in (200, 201):
            steps.append(f"✅ Created new GitHub Repository: https://github.com/{owner}/{clean_repo}")
            time.sleep(1.0)
        elif r_create.status_code == 422:
            steps.append(f"ℹ️ Using existing GitHub Repository: https://github.com/{owner}/{clean_repo}")
        else:
            return {"status": "error", "error": f"Failed to create GitHub repo: {r_create.text[:200]}"}

        # 3. Collect files to push (either the full VENOM AI platform itself or the active project)
        files_to_push: Dict[str, str] = {}
        if deploy_target == "venom_platform" or not custom_files:
            platform_files = [
                "server.py",
                "database.py",
                "providers.py",
                "venom_builder.py",
                "schema.sql",
                "requirements.txt",
                "render.yaml",
                "Dockerfile",
                "README.md",
                "static/index.html",
            ]
            for rel_path in platform_files:
                abs_p = os.path.join(BASE_DIR, rel_path)
                if os.path.exists(abs_p):
                    with open(abs_p, "r", encoding="utf-8") as f:
                        files_to_push[rel_path] = f.read()
        else:
            files_to_push = custom_files

        pushed_list = []
        for path_str, content in files_to_push.items():
            f_url = f"https://api.github.com/repos/{owner}/{clean_repo}/contents/{path_str}"
            sha = None
            rc = requests.get(f_url, headers=headers, timeout=8)
            if rc.status_code == 200:
                sha = rc.json().get("sha")
            payload = {
                "message": f"⚡ VENOM AI Auto-Deploy: {path_str}",
                "content": base64.b64encode(content.encode("utf-8")).decode("utf-8"),
            }
            if sha:
                payload["sha"] = sha
            rp = requests.put(f_url, headers=headers, json=payload, timeout=15)
            if rp.status_code in (200, 201):
                pushed_list.append(path_str)
                steps.append(f"📤 Pushed to GitHub: {path_str}")

        repo_url = f"https://github.com/{owner}/{clean_repo}"
        render_one_click_url = f"https://render.com/deploy?repo={repo_url}"
        steps.append(f"🌐 Generated Render 1-Click Free Hosting Blueprint Link: {render_one_click_url}")

        # 4. If Render API Key (rnd_...) is also provided, call Render REST API
        render_service_url = None
        rnd_key = (render_api_key or "").strip()
        if rnd_key:
            try:
                r_headers = {"Authorization": f"Bearer {rnd_key}", "Accept": "application/json", "Content-Type": "application/json"}
                r_own = requests.get("https://api.render.com/v1/owners?limit=1", headers=r_headers, timeout=10)
                if r_own.status_code == 200 and r_own.json():
                    owner_id = r_own.json()[0]["owner"]["id"]
                    r_srv = requests.post(
                        "https://api.render.com/v1/services",
                        headers=r_headers,
                        json={
                            "type": "web_service",
                            "name": clean_repo,
                            "ownerId": owner_id,
                            "repo": repo_url,
                            "autoDeploy": "yes",
                            "serviceDetails": {
                                "env": "python",
                                "plan": "free",
                                "envSpecificDetails": {
                                    "buildCommand": "pip install -r requirements.txt",
                                    "startCommand": "python server.py",
                                },
                            },
                        },
                        timeout=12,
                    )
                    if r_srv.status_code in (200, 201):
                        srv_data = r_srv.json()
                        render_service_url = srv_data.get("service", {}).get("serviceDetails", {}).get("url") or f"https://{clean_repo}.onrender.com"
                        steps.append(f"🚀 Render API Auto-Created Free Web Service: {render_service_url}")
                    else:
                        steps.append(f"ℹ️ Render API note ({r_srv.status_code}): Click the 1-Click Render Blueprint link above to finish authorizing GitHub on Render.")
                else:
                    steps.append(f"⚠️ Render API Key check returned HTTP {r_own.status_code}. Use the 1-Click Render Blueprint URL instead!")
            except Exception as e:
                steps.append(f"ℹ️ Render API notice: {str(e)}")

        return {
            "status": "ok",
            "github_owner": owner,
            "repo_url": repo_url,
            "render_blueprint_url": render_one_click_url,
            "render_live_url": render_service_url,
            "pushed_files": pushed_list,
            "steps": steps,
        }
